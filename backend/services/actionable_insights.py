"""
Proactive, prioritized business insights (Stage 7.5).

Deterministic and explainable: facts come from the shop's own records, thresholds and priority
rules come from services/insight_rules.py, and every insight lists its evidence (observed sales and
stock, forecast estimates, or configured values). Nothing is generated by a language model and
nothing is written: no purchases, stock changes or notifications are created here.

Queries (all shop-scoped, no per-product queries in this module):
1. active products;  2. sale lines in the lookback window;  3. bill totals in the lookback window;
4. the shop's first sale;  5. the last sale date of each product.
Forecasts are taken from the existing demand-forecast engine (forecast_shop_demand) through its
shared per-shop cache, so this endpoint and /insights/demand-forecast report the same estimates.
"""
