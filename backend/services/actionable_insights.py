# ------------------------------------------------------------------------------ helpers

def _utc(dt: Optional[datetime]) -> Optional[datetime]:
    """Stored timestamps may be naive (SQLite); they are UTC."""
    if dt is None:
        return None
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt.astimezone(timezone.utc)


def _since(column, start: datetime):
    """created_at >= start for both timezone-aware and naive stored values (as the other insight queries do)."""
    return or_(column >= start, column >= start.replace(tzinfo=None))


def _fmt_dt(dt: datetime) -> str:
    return dt.strftime("%d %b %Y %H:%M UTC")


def _fmt_day(d: date) -> str:
    return d.strftime("%d %b %Y")


def _qty(value, unit: str) -> str:
    return f"{format_quantity(value)} {unit}".strip()


def _plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def _days(value: float) -> str:
    v = round(float(value), 1)
    return f"{v:g} day{'' if v == 1 else 's'}"


def _pct(value: float) -> str:
    v = round(float(value), 1)
    return f"{'+' if v > 0 else ''}{v:g}%"


@dataclass
class _ProductActivity:
    units_recent: Decimal = Decimal("0")          # demand lookback window
    tx_recent: Set = field(default_factory=set)
    units_current: Decimal = Decimal("0")         # current product window
    tx_current: Set = field(default_factory=set)
    days_current: Set = field(default_factory=set)
    units_previous: Decimal = Decimal("0")        # previous product window
    tx_previous: Set = field(default_factory=set)
    units_slow_window: Decimal = Decimal("0")     # slow-moving window


@dataclass
class _Built:
    insight: ActionableInsight
    sort_value: float = 0.0


def get_shop_forecast(
    db: Session, shop_id: UUID, lead_time_days: int, as_of: Optional[datetime] = None, use_cache: bool = True
) -> ShopForecastSummary:
    """The same forecast /insights/demand-forecast returns (same cache key for the unfiltered catalogue)."""
    cache = get_forecast_cache()
    key = f"None:None:None:None:{lead_time_days}:0.3:True"
    if use_cache and as_of is None:
        cached = cache.get(shop_id, key)
        if cached is not None:
            return cached
    summary = forecast_shop_demand(db=db, shop_id=shop_id, as_of_date=as_of, lead_time_days=lead_time_days)
    if use_cache and as_of is None:
        cache.set(shop_id, key, summary)
    return summary


# ------------------------------------------------------------------------------ engine

def build_actionable_insights(
    db: Session,
    shop_id: UUID,
    *,
    now: Optional[datetime] = None,
    thresholds: InsightThresholds = DEFAULT_THRESHOLDS,
    use_forecast_cache: bool = True,
) -> Tuple[List[ActionableInsight], DailyBusinessSummary, str]:
    """Returns (insights sorted by priority, daily summary, generated_at ISO)."""
    t = thresholds
    explicit_now = now is not None
    now = _utc(now) or datetime.now(timezone.utc)
    # A caller-supplied "now" (tests, replays) also drives the forecast; the shared cache only holds "now"
    as_of = now if explicit_now else None
    today_start = now.replace(hour=0, minute=0, second=0, microsecond=0)
    last_complete_day = today_start.date() - timedelta(days=1)

    lookback_days = max(
        t.demand_lookback_days,
        t.slow_moving_window_days,
        2 * t.product_window_days,
        2 * t.sales_trend_window_days,
        t.unusual_day_lookback_days + 2,
    )
    window_start = now - timedelta(days=lookback_days)
    demand_start = now - timedelta(days=t.demand_lookback_days)
    cur_start = now - timedelta(days=t.product_window_days)
    prev_start = now - timedelta(days=2 * t.product_window_days)
    slow_start = now - timedelta(days=t.slow_moving_window_days)

    # 1. Products
    products: List[Product] = (
        db.query(Product).filter(Product.shop_id == shop_id, Product.is_active == True).order_by(Product.name.asc()).all()  # noqa: E712
    )

    # 2. Sale lines in the window (positive quantities only, as the forecast engine counts them)
    line_rows = (
        db.query(SaleItem.product_id, SaleItem.quantity, SaleItem.sale_id, Sale.created_at)
        .join(Sale, SaleItem.sale_id == Sale.id)
        .filter(Sale.shop_id == shop_id, SaleItem.quantity > 0, _since(Sale.created_at, window_start))
        .all()
    )
    # 3. Bill totals in the window
    bill_rows = (
        db.query(Sale.id, Sale.created_at, Sale.total_amount)
        .filter(Sale.shop_id == shop_id, _since(Sale.created_at, window_start))
        .all()
    )
    # 4. First sale ever (history coverage)
    first_sale = _utc(db.query(func.min(Sale.created_at)).filter(Sale.shop_id == shop_id).scalar())
    # 5. Last sale date per product
    last_sold: Dict[UUID, datetime] = {
        pid: _utc(ts)
        for pid, ts in (
            db.query(SaleItem.product_id, func.max(Sale.created_at))
            .join(Sale, SaleItem.sale_id == Sale.id)
            .filter(Sale.shop_id == shop_id, SaleItem.quantity > 0)
            .group_by(SaleItem.product_id)
            .all()
        )
    }

    # Per-product activity
    activity: Dict[UUID, _ProductActivity] = {}
    products_sold_today: Set[UUID] = set()
    for pid, qty, sale_id, ts in line_rows:
        ts = _utc(ts)
        if ts is None or ts < window_start or ts > now:
            continue
        q = to_decimal(qty) or Decimal("0")
        a = activity.setdefault(pid, _ProductActivity())
        if ts >= demand_start:
            a.units_recent += q
            a.tx_recent.add(sale_id)
        if ts >= slow_start:
            a.units_slow_window += q
        if ts >= cur_start:
            a.units_current += q
            a.tx_current.add(sale_id)
            a.days_current.add(ts.date())
        elif ts >= prev_start:
            a.units_previous += q
            a.tx_previous.add(sale_id)
        if ts >= today_start:
            products_sold_today.add(pid)

    # Shop-level bill aggregates
    bills = [(_utc(ts), amt) for _, ts, amt in bill_rows]
    bills = [(ts, amt) for ts, amt in bills if ts is not None and window_start <= ts <= now]

    def total(start: datetime, end: datetime, inclusive_end: bool = True) -> Tuple[Decimal, int]:
        sel = [amt for ts, amt in bills if ts >= start and (ts <= end if inclusive_end else ts < end)]
        return round_currency(sum_decimal(sel)), len(sel)

    today_total, today_tx = total(today_start, now)
    yday_start = today_start - timedelta(days=1)
    yday_same_total, yday_same_tx = total(yday_start, now - timedelta(days=1), inclusive_end=True)

    # Forecast (existing engine). A failure is reported, never replaced.
    forecast: Optional[ShopForecastSummary] = None
    try:
        forecast = get_shop_forecast(db, shop_id, t.lead_time_days, as_of=as_of, use_cache=use_forecast_cache)
    except Exception:  # pragma: no cover - defensive; logged and reported as a data note
        logger.exception("Demand forecast failed for shop %s", shop_id)
    fc_by_pid: Dict[UUID, ProductDemandForecast] = {f.product_id: f for f in (forecast.forecasts if forecast else [])}

    built: List[_Built] = []
    data_notes: List[str] = []

    def add(sort_value: float = 0.0, **kw) -> None:
        built.append(_Built(ActionableInsight(**kw), sort_value))

    window_obs = (_fmt_dt(demand_start), _fmt_dt(now))

    # -------------------------------------------------------------- inventory risk and low stock
    too_new: List[str] = []
    for p in products:
        pid = p.id
        unit = p.unit or "pcs"
        stock = to_decimal(p.current_stock) or Decimal("0")
        stock_n = quantity_number(stock)
        threshold_set = p.reorder_level is not None and p.reorder_level > 0
        threshold_n = quantity_number(p.reorder_level) if threshold_set else None
        a = activity.get(pid, _ProductActivity())
        f = fc_by_pid.get(pid)
        n_recent = len(a.tx_recent)
        created = _utc(p.created_at)
        age_days = (now - created).days if created else None

        reorder_hint = ""
        if f is not None and f.recommended_reorder_quantity:
            qualifiers = [f"{f.confidence_level.value.lower()} confidence"]
            if f.is_reorder_provisional:
                qualifiers.append("provisional")
            reorder_hint = (
                f" The forecast suggests about {_qty(f.recommended_reorder_quantity, unit)} ({', '.join(qualifiers)}),"
                f" assuming a {t.lead_time_days}-day lead time; this is advisory."
            )

        def stock_ev() -> InsightEvidence:
            return InsightEvidence(label="Current stock", value=_qty(stock, unit), source=OBS)

        def threshold_ev() -> InsightEvidence:
            return InsightEvidence(label="Minimum stock level", value=_qty(p.reorder_level, unit), source=CFG)

        def recent_ev() -> InsightEvidence:
            return InsightEvidence(
                label=f"Sold in the last {t.demand_lookback_days} days",
                value=f"{_qty(a.units_recent, unit)} in {_plural(n_recent, 'transaction')}",
                source=OBS,
            )

        merged_low_stock = False
        if stock <= 0:
            priority = rules.out_of_stock_priority(float(a.units_recent))
            has_demand = a.units_recent > 0
            ev = [stock_ev()]
            if has_demand:
                ev.append(recent_ev())
            if pid in last_sold:
                ev.append(InsightEvidence(label="Last sold", value=_fmt_dt(last_sold[pid]), source=OBS))
            elif not has_demand:
                ev.append(InsightEvidence(label="Sales history", value="No sales recorded", source=OBS))
            if threshold_set:
                ev.append(threshold_ev())
            add(
                sort_value=-float(a.units_recent),
                id=f"{'out_of_stock_with_demand' if has_demand else 'out_of_stock'}:{pid}",
                type="out_of_stock_with_demand" if has_demand else "out_of_stock",
                category=InsightCategory.INVENTORY_RISK,
                priority=priority,
                title=f"{p.name} is out of stock",
                description=(
                    f"{p.name} has no stock left and sold {_qty(a.units_recent, unit)} in the last "
                    f"{t.demand_lookback_days} days, so customers may be turned away."
                    if has_demand
                    else f"{p.name} has no stock left. It has not sold in the last {t.demand_lookback_days} days."
                ),
                evidence=ev,
                product_id=pid, product_name=p.name, unit=unit,
                current_value=stock_n, threshold_value=threshold_n,
                observation_start=window_obs[0], observation_end=window_obs[1],
                data_quality=rules.observed_quality(n_recent, t) if has_demand else DataQuality.HIGH,
                suggested_action=(
                    f"Restock {p.name}.{reorder_hint}" if has_demand
                    else f"Check whether {p.name} should still be stocked before reordering."
                ),
                is_actionable=True,
            )
            continue

        # In stock: forecast-based run-out (never for products without demand history)
        if (
            f is not None
            and f.forecast_tier != ForecastTier.TIER_3_COLD_START
            and f.days_to_stockout is not None
            and (f.daily_demand_rate or 0) > 0
        ):
            priority = rules.forecast_stockout_priority(f.days_to_stockout, f.confidence_level, t)
            if priority is not None:
                imminent = f.days_to_stockout <= t.lead_time_days
                ev = [
                    stock_ev(),
                    InsightEvidence(label="Estimated daily demand", value=_qty(f.daily_demand_rate, unit), source=FC),
                ]
                if f.expected_seven_day_demand is not None:
                    ev.append(InsightEvidence(label="Expected demand over 7 days", value=_qty(f.expected_seven_day_demand, unit), source=FC))
                ev.append(InsightEvidence(label="Projected stock cover", value=_days(f.days_to_stockout), source=FC))
                ev.append(InsightEvidence(
                    label="Forecast confidence",
                    value=f"{f.confidence_level.value} ({f.total_valid_sales} sales over {_plural(f.observable_days, 'day')})",
                    source=FC,
                ))
                for w in f.warnings:
                    if w.startswith(("Intermittent demand", "Sparse sales history")):
                        ev.append(InsightEvidence(label="Forecast note", value=w, source=FC))
                if threshold_set and stock <= Decimal(str(p.reorder_level)):
                    ev.append(threshold_ev())
                    merged_low_stock = True
                insufficient = (
                    f.expected_seven_day_demand is not None and Decimal(str(f.expected_seven_day_demand)) > stock
                )
                add(
                    sort_value=float(f.days_to_stockout),
                    id=f"{'imminent_stockout' if imminent else 'stockout_within_7_days'}:{pid}",
                    type="imminent_stockout" if imminent else "stockout_within_7_days",
                    category=InsightCategory.INVENTORY_RISK,
                    priority=priority,
                    title=(
                        f"{p.name} may run out within {t.lead_time_days} days" if imminent
                        else f"{p.name} may run out within {t.stockout_watch_days} days"
                    ),
                    description=(
                        f"At the estimated rate of {_qty(f.daily_demand_rate, unit)} per day, the current "
                        f"{_qty(stock, unit)} would last about {_days(f.days_to_stockout)}"
                        + (", less than the expected demand for the next 7 days." if insufficient else ".")
                        + (" This estimate rests on limited sales history." if f.confidence_level == ConfidenceLevel.LOW else "")
                    ),
                    evidence=ev,
                    product_id=pid, product_name=p.name, unit=unit,
                    current_value=stock_n, threshold_value=threshold_n,
                    observation_start=_fmt_dt(now - timedelta(days=max(f.observable_days - 1, 0))),
                    observation_end=_fmt_dt(now),
                    data_quality=rules.forecast_quality(f.confidence_level),
                    suggested_action=f"Plan a purchase of {p.name} now.{reorder_hint}",
                    is_actionable=True,
                )

        # Below the configured minimum (not already reported with a stockout alert)
        if threshold_set and not merged_low_stock and stock <= Decimal(str(p.reorder_level)):
            ev = [stock_ev(), threshold_ev()]
            if a.units_recent > 0:
                ev.append(recent_ev())
            add(
                sort_value=float(stock / Decimal(str(p.reorder_level))),
                id=f"below_minimum_stock:{pid}",
                type="below_minimum_stock",
                category=InsightCategory.LOW_STOCK,
                priority=rules.low_stock_priority(),
                title=f"{p.name} is below its minimum stock level",
                description=f"{p.name} has {_qty(stock, unit)}, at or below the minimum of {_qty(p.reorder_level, unit)} set for it.",
                evidence=ev,
                product_id=pid, product_name=p.name, unit=unit,
                current_value=stock_n, threshold_value=threshold_n,
                data_quality=DataQuality.HIGH,
                suggested_action=f"Restock {p.name} above {_qty(p.reorder_level, unit)}.{reorder_hint}",
                is_actionable=True,
            )

        # Slow-moving stock / excess stock (only with a full observation window)
        if age_days is None or age_days < t.slow_moving_min_product_age_days:
            if a.units_slow_window <= 0:
                too_new.append(p.name)
        elif a.units_slow_window <= 0:
            ev = [
                stock_ev(),
                InsightEvidence(label=f"Sales in the last {t.slow_moving_window_days} days", value="None", source=OBS),
                InsightEvidence(
                    label="Last sold",
                    value=_fmt_dt(last_sold[pid]) if pid in last_sold else "Never recorded",
                    source=OBS,
                ),
                InsightEvidence(label="Product added", value=_fmt_day(created.date()), source=OBS),
            ]
            add(
                sort_value=-float(stock),
                id=f"no_sales_in_window:{pid}",
                type="no_sales_in_window",
                category=InsightCategory.SLOW_MOVING,
                priority=rules.slow_moving_priority(),
                title=f"{p.name} has not sold in {t.slow_moving_window_days} days",
                description=(
                    f"{_qty(stock, unit)} of {p.name} is in stock, with no sales recorded in the last "
                    f"{t.slow_moving_window_days} days."
                ),
                evidence=ev,
                product_id=pid, product_name=p.name, unit=unit, current_value=stock_n,
                observation_start=_fmt_dt(slow_start), observation_end=_fmt_dt(now),
                data_quality=DataQuality.HIGH,
                suggested_action=f"Review the price, shelf placement or need to keep stocking {p.name} before buying more.",
                is_actionable=True,
            )
        elif n_recent >= t.excess_stock_min_transactions and a.units_recent > 0:
            daily_rate = a.units_recent / Decimal(t.demand_lookback_days)
            cover = stock / daily_rate
            if cover > Decimal(str(t.excess_stock_cover_days)):
                add(
                    sort_value=-float(cover),
                    id=f"excess_stock:{pid}",
                    type="excess_stock",
                    category=InsightCategory.INVENTORY_OPPORTUNITY,
                    priority=rules.excess_stock_priority(),
                    title=f"{p.name} stock is high for its sales rate",
                    description=(
                        f"At the recorded rate of {_qty(quantity_number(daily_rate), unit)} per day, the "
                        f"{_qty(stock, unit)} in stock would last about {_days(float(cover))}."
                    ),
                    evidence=[
                        stock_ev(),
                        recent_ev(),
                        InsightEvidence(label="Observed daily rate", value=_qty(quantity_number(daily_rate), unit), source=OBS),
                        InsightEvidence(label="Stock cover at that rate", value=_days(float(cover)), source=OBS),
                    ],
                    product_id=pid, product_name=p.name, unit=unit, current_value=stock_n,
                    observation_start=window_obs[0], observation_end=window_obs[1],
                    data_quality=rules.observed_quality(n_recent, t),
                    suggested_action=f"Hold off on new purchases of {p.name} until stock comes down (advisory).",
                    is_actionable=True,
                )

    # -------------------------------------------------------------- fast-moving and replenishment
    names = {p.id: p for p in products}
    candidates = [
        (pid, a) for pid, a in activity.items()
        if pid in names
        and len(a.tx_current) >= t.fast_moving_min_transactions
        and len(a.days_current) >= t.fast_moving_min_active_days
    ]
    cur_obs = (_fmt_dt(cur_start), _fmt_dt(now))
    increasing: Set[UUID] = set()
    for pid, a in candidates:
        p = names[pid]
        unit = p.unit or "pcs"
        if (
            len(a.tx_previous) >= t.increasing_demand_min_previous_transactions
            and a.units_previous > 0
        ):
            growth = float((a.units_current - a.units_previous) / a.units_previous * 100)
            if growth >= t.increasing_demand_min_growth_pct:
                increasing.add(pid)
                add(
                    sort_value=-growth,
                    id=f"increasing_demand:{pid}",
                    type="increasing_demand",
                    category=InsightCategory.FAST_MOVING,
                    priority=rules.fast_moving_priority(),
                    title=f"Demand for {p.name} is rising",
                    description=(
                        f"{p.name} sold {_qty(a.units_current, unit)} in the last {t.product_window_days} days, "
                        f"up from {_qty(a.units_previous, unit)} in the {t.product_window_days} days before ({_pct(growth)}). "
                        "This is recorded sales, not a forecast."
                    ),
                    evidence=[
                        InsightEvidence(label=f"Last {t.product_window_days} days", value=f"{_qty(a.units_current, unit)} in {_plural(len(a.tx_current), 'transaction')}", source=OBS),
                        InsightEvidence(label=f"Previous {t.product_window_days} days", value=f"{_qty(a.units_previous, unit)} in {_plural(len(a.tx_previous), 'transaction')}", source=OBS),
                        InsightEvidence(label="Change", value=_pct(growth), source=OBS),
                    ],
                    product_id=pid, product_name=p.name, unit=unit, current_value=quantity_number(a.units_current),
                    observation_start=_fmt_dt(prev_start), observation_end=_fmt_dt(now),
                    data_quality=rules.observed_quality(min(len(a.tx_current), len(a.tx_previous)), t),
                    is_actionable=False,
                )

    ranked = sorted(
        candidates,
        key=lambda item: (-len(item[1].tx_current), -float(item[1].units_current), names[item[0]].name),
    )[: t.fast_moving_top_n]
    for rank, (pid, a) in enumerate(ranked, start=1):
        if pid in increasing:
            continue
        p = names[pid]
        unit = p.unit or "pcs"
        f = fc_by_pid.get(pid)
        ev = [
            InsightEvidence(label=f"Sold in the last {t.product_window_days} days", value=f"{_qty(a.units_current, unit)} in {_plural(len(a.tx_current), 'transaction')}", source=OBS),
            InsightEvidence(label="Days with sales", value=str(len(a.days_current)), source=OBS),
        ]
        if f is not None and f.daily_demand_rate:
            ev.append(InsightEvidence(label="Estimated daily demand (forecast)", value=_qty(f.daily_demand_rate, unit), source=FC))
        add(
            sort_value=float(rank),
            id=f"high_volume_product:{pid}",
            type="high_volume_product",
            category=InsightCategory.FAST_MOVING,
            priority=rules.fast_moving_priority(),
            title=f"{p.name} is one of your most frequently sold products",
            description=(
                f"{p.name} appeared in {_plural(len(a.tx_current), 'transaction')} on {_plural(len(a.days_current), 'day')} "
                f"in the last {t.product_window_days} days (rank {rank} by number of sales)."
            ),
            evidence=ev,
            product_id=pid, product_name=p.name, unit=unit, current_value=quantity_number(a.units_current),
            observation_start=cur_obs[0], observation_end=cur_obs[1],
            data_quality=rules.observed_quality(len(a.tx_current), t),
            is_actionable=False,
        )

    for pid, a in candidates:
        p = names[pid]
        f = fc_by_pid.get(pid)
        stock = to_decimal(p.current_stock) or Decimal("0")
        if (
            f is None or stock <= 0 or f.days_to_stockout is None
            or f.confidence_level == ConfidenceLevel.NONE
            or not (t.stockout_watch_days < f.days_to_stockout <= t.replenishment_horizon_days)
        ):
            continue
        unit = p.unit or "pcs"
        add(
            sort_value=float(f.days_to_stockout),
            id=f"replenishment_planning:{pid}",
            type="replenishment_planning",
            category=InsightCategory.INVENTORY_OPPORTUNITY,
            priority=rules.replenishment_priority(),
            title=f"Plan replenishment for {p.name}",
            description=(
                f"{p.name} sells steadily ({_plural(len(a.tx_current), 'sale')} in {t.product_window_days} days) and its "
                f"{_qty(stock, unit)} is forecast to last about {_days(f.days_to_stockout)}."
            ),
            evidence=[
                InsightEvidence(label="Current stock", value=_qty(stock, unit), source=OBS),
                InsightEvidence(label=f"Sold in the last {t.product_window_days} days", value=f"{_qty(a.units_current, unit)} in {_plural(len(a.tx_current), 'transaction')}", source=OBS),
                InsightEvidence(label="Projected stock cover", value=_days(f.days_to_stockout), source=FC),
                InsightEvidence(label="Forecast confidence", value=f.confidence_level.value, source=FC),
            ],
            product_id=pid, product_name=p.name, unit=unit, current_value=quantity_number(stock),
            observation_start=cur_obs[0], observation_end=cur_obs[1],
            data_quality=rules.forecast_quality(f.confidence_level),
            suggested_action=(
                f"Include {p.name} in your next purchase."
                + (f" Forecast suggestion: about {_qty(f.recommended_reorder_quantity, unit)} (advisory)." if f.recommended_reorder_quantity else "")
            ),
            is_actionable=True,
        )

    if too_new:
        shown = ", ".join(sorted(too_new)[:5]) + (f" and {len(too_new) - 5} more" if len(too_new) > 5 else "")
        add(
            sort_value=0,
            id="too_new_to_assess:shop",
            type="too_new_to_assess",
            category=InsightCategory.DATA_QUALITY,
            priority=InsightPriority.INFO,
            title=f"{_plural(len(too_new), 'product')} too new to judge movement",
            description=(
                f"These products were added less than {t.slow_moving_min_product_age_days} days ago (or have no "
                "creation date) and have not sold yet, so they are not classed as slow-moving."
            ),
            evidence=[InsightEvidence(label="Products", value=shown, source=OBS)],
            data_quality=DataQuality.INSUFFICIENT,
            is_actionable=False,
        )

    # -------------------------------------------------------------- shop sales trend
    w = t.sales_trend_window_days
    tr_cur_start = now - timedelta(days=w)
    tr_prev_start = now - timedelta(days=2 * w)
    cur_total, cur_tx = total(tr_cur_start, now)
    prev_total, prev_tx = total(tr_prev_start, tr_cur_start, inclusive_end=False)
    covered = first_sale is not None and first_sale <= tr_prev_start
    if first_sale is None:
        add(
            id="no_sales_recorded:shop", type="no_sales_recorded",
            category=InsightCategory.DATA_QUALITY, priority=InsightPriority.INFO,
            title="No sales recorded yet",
            description="Sales trends, fast-moving and slow-moving products appear once sales are recorded.",
            evidence=[InsightEvidence(label="Transactions", value="0", source=OBS)],
            data_quality=DataQuality.INSUFFICIENT, is_actionable=False,
        )
        data_notes.append("No sales recorded yet, so there are no sales trends.")
    elif not covered or cur_tx < t.sales_trend_min_transactions_per_window or prev_tx < t.sales_trend_min_transactions_per_window:
        reason = (
            f"sales history starts {_fmt_dt(first_sale)}, which does not cover the previous {w}-day period"
            if not covered
            else f"each {w}-day period needs at least {t.sales_trend_min_transactions_per_window} transactions "
            f"(current: {cur_tx}, previous: {prev_tx})"
        )
        add(
            id="insufficient_sales_history:shop", type="insufficient_sales_history",
            category=InsightCategory.DATA_QUALITY, priority=InsightPriority.INFO,
            title="Not enough sales history for a trend",
            description=f"No sales trend is reported because {reason}.",
            evidence=[
                InsightEvidence(label=f"Last {w} days", value=f"{format_rupees(cur_total)} in {_plural(cur_tx, 'transaction')}", source=OBS),
                InsightEvidence(label=f"Previous {w} days", value=f"{format_rupees(prev_total)} in {_plural(prev_tx, 'transaction')}", source=OBS),
            ],
            observation_start=_fmt_dt(tr_prev_start), observation_end=_fmt_dt(now),
            data_quality=DataQuality.INSUFFICIENT, is_actionable=False,
        )
        data_notes.append(f"Sales trend not assessed: {reason}.")
    elif prev_total > 0:
        change = float((cur_total - prev_total) / prev_total * 100)
        priority = rules.sales_trend_priority(change, t)
        ev = [
            InsightEvidence(label=f"Last {w} days ({_fmt_dt(tr_cur_start)} – {_fmt_dt(now)})", value=f"{format_rupees(cur_total)} in {_plural(cur_tx, 'transaction')}", source=OBS),
            InsightEvidence(label=f"Previous {w} days ({_fmt_dt(tr_prev_start)} – {_fmt_dt(tr_cur_start)})", value=f"{format_rupees(prev_total)} in {_plural(prev_tx, 'transaction')}", source=OBS),
            InsightEvidence(label="Change", value=_pct(change), source=OBS),
        ]
        common = dict(
            category=InsightCategory.SALES_TREND, evidence=ev,
            current_value=to_number(cur_total), threshold_value=to_number(prev_total),
            observation_start=_fmt_dt(tr_prev_start), observation_end=_fmt_dt(now),
            data_quality=rules.observed_quality(min(cur_tx, prev_tx), t),
        )
        if priority is None:
            add(
                id="sales_stable:shop", type="sales_stable", priority=InsightPriority.INFO,
                title=f"Sales are steady ({_pct(change)} vs the previous {w} days)",
                description=f"The change is within ±{t.sales_trend_significant_pct:g}%, so it is not treated as significant.",
                is_actionable=False, **common,
            )
        elif change < 0:
            add(
                id="sales_decline:shop", type="sales_decline", priority=priority,
                title=f"Sales are down {abs(round(change, 1)):g}% vs the previous {w} days",
                description=f"Sales in the last {w} days were {format_rupees(cur_total)}, compared with {format_rupees(prev_total)} in the {w} days before.",
                suggested_action="Compare product sales between the two periods (Sales Insights) and check for stock-outs of usual sellers.",
                is_actionable=True, **common,
            )
        else:
            add(
                id="sales_increase:shop", type="sales_increase", priority=priority,
                title=f"Sales are up {round(change, 1):g}% vs the previous {w} days",
                description=f"Sales in the last {w} days were {format_rupees(cur_total)}, compared with {format_rupees(prev_total)} in the {w} days before.",
                is_actionable=False, **common,
            )

    # Unusual day: the last complete UTC day vs the average of the days before it
    lb = t.unusual_day_lookback_days
    lb_first = last_complete_day - timedelta(days=lb)
    if first_sale is not None and first_sale.date() <= lb_first:
        day_totals: Dict[date, List] = {}
        for ts, amt in bills:
            day_totals.setdefault(ts.date(), []).append(amt)
        lookback = [round_currency(sum_decimal(day_totals.get(lb_first + timedelta(days=i), []))) for i in range(lb)]
        active_days = sum(1 for d in range(lb) if day_totals.get(lb_first + timedelta(days=d)))
        day_total = round_currency(sum_decimal(day_totals.get(last_complete_day, [])))
        avg = sum(lookback, Decimal("0")) / Decimal(lb)
        if active_days >= t.unusual_day_min_active_days and avg > 0:
            ratio = float(day_total / avg)
            priority = rules.unusual_day_priority(ratio, t)
            if priority is not None:
                low = ratio <= t.unusual_day_low_ratio
                add(
                    id=f"{'unusually_low_day' if low else 'unusually_high_day'}:shop",
                    type="unusually_low_day" if low else "unusually_high_day",
                    category=InsightCategory.SALES_TREND, priority=priority,
                    title=f"Sales on {_fmt_day(last_complete_day)} were unusually {'low' if low else 'high'}",
                    description=(
                        f"{format_rupees(day_total)} on {_fmt_day(last_complete_day)}, against an average of "
                        f"{format_rupees(round_currency(avg))} per day over the previous {lb} days ({ratio:.2f}x)."
                    ),
                    evidence=[
                        InsightEvidence(label=_fmt_day(last_complete_day), value=format_rupees(day_total), source=OBS),
                        InsightEvidence(label=f"Daily average, {_fmt_day(lb_first)} – {_fmt_day(last_complete_day - timedelta(days=1))}", value=format_rupees(round_currency(avg)), source=OBS),
                        InsightEvidence(label="Days with sales in that period", value=f"{active_days} of {lb}", source=OBS),
                    ],
                    current_value=to_number(day_total), threshold_value=to_number(round_currency(avg)),
                    observation_start=_fmt_day(lb_first), observation_end=_fmt_day(last_complete_day),
                    data_quality=rules.observed_quality(active_days, t),
                    suggested_action="Check whether anything unusual happened that day (closure, stock-outs, a large order)." if low else None,
                    is_actionable=low,
                )

    if not products:
        add(
            id="no_products:shop", type="no_products",
            category=InsightCategory.DATA_QUALITY, priority=InsightPriority.INFO,
            title="No active products",
            description="Add products to see inventory insights.",
            evidence=[InsightEvidence(label="Active products", value="0", source=OBS)],
            data_quality=DataQuality.INSUFFICIENT, is_actionable=False,
        )
    if forecast is None:
        data_notes.append("The demand forecast could not be computed, so forecast-based alerts are missing.")

    # -------------------------------------------------------------- order and summarize
    built.sort(key=lambda b: (
        PRIORITY_RANK[b.insight.priority],
        CATEGORY_ORDER[b.insight.category],
        b.sort_value,
        b.insight.product_name or "",
        b.insight.id,
    ))
    insights = [b.insight for b in built]

    urgent = [i for i in insights if i.priority in (InsightPriority.CRITICAL, InsightPriority.HIGH)]
    positive = [i for i in insights if i.type in POSITIVE_TYPES]
    highlights = [i.title for i in urgent[:3]] or ["No urgent issues found in the current records."]
    highlights += [i.title for i in positive[:2]]

    summary = DailyBusinessSummary(
        period_start=today_start.isoformat(),
        period_end=now.isoformat(),
        today_sales=to_number(today_total),
        today_transactions=today_tx,
        products_sold_today=len(products_sold_today),
        same_time_yesterday_sales=to_number(yday_same_total),
        same_time_yesterday_transactions=yday_same_tx,
        out_of_stock_count=sum(1 for p in products if (to_decimal(p.current_stock) or 0) <= 0),
        below_minimum_count=sum(
            1 for p in products
            if p.reorder_level is not None and p.reorder_level > 0
            and Decimal("0") < (to_decimal(p.current_stock) or Decimal("0")) <= Decimal(str(p.reorder_level))
        ),
        forecast_stockout_risk_count=(
            sum(1 for i in insights if i.type in ("imminent_stockout", "stockout_within_7_days")) if forecast is not None else None
        ),
        highlights=highlights,
        data_notes=data_notes,
        has_sales_history=first_sale is not None,
    )
    return insights, summary, now.isoformat()
